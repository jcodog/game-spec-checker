import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';

// Run only against a locally launched GameSpec WebView with debugging explicitly enabled.
// This exercises the real Tauri IPC and real scanner; it injects no hardware mocks.
const browser = await chromium.connectOverCDP('http://127.0.0.1:9222');
const page = browser.contexts().flatMap(c => c.pages()).find(p => p.url().includes('tauri.localhost') || p.url().startsWith('tauri://'));
assert(page, 'GameSpec desktop WebView not found. Launch the app with WEBVIEW2_ADDITIONAL_BROWSER_ARGUMENTS=--remote-debugging-port=9222.');
const errors = [];
page.on('pageerror', e => errors.push(e.message));
await page.getByRole('button', { name: 'Your system', exact: true }).waitFor();
await page.getByText('Hardware detected', { exact: true }).waitFor({ timeout: 60000 });
assert.equal(await page.getByRole('alert').count(), 0);
await page.getByRole('button', { name: 'Game library' }).click();
await page.getByRole('button', { name: 'Add game', exact: true }).click();
await page.getByLabel('Game name', { exact: true }).fill('Desktop verification game');
await page.getByLabel('Game version', { exact: true }).fill('Verification only');
await page.getByRole('button', { name: 'Save game profile' }).click();
const row = page.locator('.game-row').filter({ hasText: 'Desktop verification game' });
await row.waitFor();
await row.getByRole('button', { name: 'Edit', exact: true }).click();
await page.getByLabel('Game version', { exact: true }).fill('Edited and persisted');
await page.getByRole('button', { name: 'Save game profile' }).click();
await row.getByText('Edited and persisted', { exact: true }).waitFor();
await row.getByRole('button', { name: 'Assess', exact: true }).click();
const adapter = page.getByLabel('Gaming GPU', { exact: true });
const values = await adapter.locator('option').evaluateAll(options => options.map(o => o.value).filter(Boolean));
if (values.length) await adapter.selectOption(values[0]);
await page.getByRole('button', { name: 'Check compatibility' }).click();
await page.getByText('Assessment result', { exact: true }).waitFor({ timeout: 60000 });
assert.equal(await page.locator('.report-table details').count(), 8);
await page.locator('.report-table summary').first().click();
await page.getByText('Minimum evidence', { exact: true }).waitFor();
await page.getByLabel('Resolution profile', { exact: true }).selectOption('2560x1440');
await page.getByLabel('Starting preset', { exact: true }).selectOption('Ultra');
await page.locator('.recommendations').getByText('Ultra', { exact: true }).first().waitFor();
await page.getByLabel('Observed FPS', { exact: true }).fill('30');
await page.getByLabel('Target FPS', { exact: true }).fill('60');
await page.getByRole('heading', { name: 'Measured tuning', exact: true }).waitFor();
await page.getByRole('button', { name: 'Settings & diagnostics', exact: true }).click();
await page.getByLabel('Theme', { exact: true }).selectOption('light');
assert.equal(await page.locator('html').getAttribute('data-theme'), 'light');
await page.getByLabel('Theme', { exact: true }).selectOption('dark');
assert.equal(await page.locator('html').getAttribute('data-theme'), 'dark');
await page.getByRole('button', { name: 'Game library' }).click();
await page.getByRole('button', { name: 'Delete Desktop verification game', exact: true }).click();
await row.waitFor({ state: 'detached' });
await page.getByRole('button', { name: 'Your system', exact: true }).click();
assert.deepEqual(errors, []);
mkdirSync('.local', { recursive: true });
await page.screenshot({ path: '.local/desktop-verified.png', fullPage: true });
writeFileSync(path.join('.local', 'desktop-verification.json'), JSON.stringify({ realTauriIpc: true, navigation: true, profileCreateEditDelete: true, assessmentComponents: 8, graphicsTuning: true, themes: true, pageErrors: errors }, null, 2));
console.log('Desktop verification passed: real scanning, profile persistence, assessment, graphics tuning, navigation, themes.');
await browser.close();
